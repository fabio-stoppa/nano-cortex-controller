/// Mirror of `lv_image_header_t`. LVGL declares it as `uint32_t` bitfields of
/// 8/8/16 + 16/16/16/16 bits, which on this little-endian target is exactly
/// this field layout.
#[repr(C)]
struct ImageHeader {
    magic: u8,
    cf: u8,
    flags: u16,
    w: u16,
    h: u16,
    stride: u16,
    reserved_2: u16,
}

/// Mirror of `lv_image_dsc_t`.
#[repr(C)]
pub struct ImageDsc {
    header: ImageHeader,
    data_size: u32,
    data: *const u8,
    reserved: *const c_void,
    reserved_2: *const c_void,
}

// Read-only pixel data shared with the LVGL renderer.
unsafe impl Sync for ImageDsc {}

impl ImageDsc {
    pub fn as_src(&'static self) -> *const c_void {
        self as *const ImageDsc as *const c_void
    }
}

pub static TUNER_FORK: ImageDsc = ImageDsc {
    header: ImageHeader {
        magic: esp_idf_svc::sys::LV_IMAGE_HEADER_MAGIC as u8,
        cf: esp_idf_svc::sys::lv_color_format_t_LV_COLOR_FORMAT_A8 as u8,
        flags: 0,
        w: TUNER_FORK_W,
        h: TUNER_FORK_H,
        stride: 0,
        reserved_2: 0,
    },
    data_size: TUNER_FORK_MAP.len() as u32,
    data: TUNER_FORK_MAP.as_ptr(),
    reserved: ptr::null(),
    reserved_2: ptr::null(),
};

/// LVGL reads this by pointer, so hold the mirror against the bindgen view of
/// `lv_image_dsc_t`: any header drift has to break the build, not the display.
const _: () = {
    use core::mem::{align_of, offset_of, size_of};
    use esp_idf_svc::sys as sys;

    assert!(size_of::<ImageDsc>() == size_of::<sys::lv_image_dsc_t>());
    assert!(align_of::<ImageDsc>() == align_of::<sys::lv_image_dsc_t>());
    assert!(offset_of!(ImageDsc, data_size) == offset_of!(sys::lv_image_dsc_t, data_size));
    assert!(offset_of!(ImageDsc, data) == offset_of!(sys::lv_image_dsc_t, data));
    assert!(size_of::<ImageHeader>() == size_of::<sys::lv_image_header_t>());
};
